/**
 * NVIDIA Nemotron Client via Nebius Token Factory
 *
 * Interacts with the official Nebius Token Factory OpenAI-compatible REST API.
 * Keeps all API keys strictly on the server.
 * Never modifies or fabricates calculation results.
 */

import { ComparisonAnalysisResult, AiReviewResponse } from '../src/types/cost';
import { generateMockNemotronReview } from './mockNemotron';

const DEFAULT_NEBIUS_BASE_URL = 'https://api.tokenfactory.us-central1.nebius.com/v1';
const DEFAULT_MODEL = 'nvidia/Llama-3.1-Nemotron-70B-Instruct-HF';

export interface NebiusClientConfig {
  apiKey?: string;
  baseUrl?: string;
  model?: string;
  timeoutMs?: number;
}

export async function explainComparisonWithNemotron(
  analysis: ComparisonAnalysisResult,
  configOverride?: NebiusClientConfig
): Promise<AiReviewResponse> {
  const apiKey = configOverride?.apiKey || process.env.NEBIUS_API_KEY;
  const baseUrl = (configOverride?.baseUrl || process.env.NEBIUS_BASE_URL || DEFAULT_NEBIUS_BASE_URL).replace(/\/+$/, '');
  const model = configOverride?.model || process.env.NEBIUS_MODEL || DEFAULT_MODEL;
  const timeoutMs = configOverride?.timeoutMs || 25000;

  // If no API key is provided, gracefully serve verified mock reasoning with explicit labelling
  if (!apiKey || apiKey.trim() === '' || apiKey.trim() === 'your_nebius_api_key_here') {
    return generateMockNemotronReview(analysis);
  }

  const systemPrompt = `You are VeraCost Senior Decision & Financial Analyst powered by NVIDIA Nemotron.
You analyze transparent Total Cost of Ownership (TCO) calculations.
CRITICAL CONSTRAINT: You MUST NOT invent, alter, or recalculate the numeric results. All calculations are deterministically computed by VeraCost's verified engine.
Your role is to explain the cost breakdown, highlight key drivers, identify missing/unverified assumptions, suggest overlooked expenses, and describe scenario sensitivities.

Respond ONLY with a valid JSON object matching this exact structure:
{
  "executiveSummary": "Concise 2-3 sentence overview identifying the lowest TCO option, net savings, and key percentage advantage.",
  "lowestCostExplanation": "Clear explanation of why this option won (e.g. upfront price advantage vs operating efficiency).",
  "driverBreakdown": [
    {
      "factor": "Driver Title",
      "description": "Explanation of impact",
      "recommendation": "Actionable advice for the user"
    }
  ],
  "missingAssumptionsFlags": [
    "Specific missing or unestimated assumption flag"
  ],
  "hiddenCostSuggestions": [
    {
      "category": "Cost Category",
      "costName": "Suggested Item",
      "typicalRange": "Estimated dollar range",
      "rational": "Why this item matters"
    }
  ],
  "scenarioSensitivityNotes": "How results shift between lower-cost and higher-cost stress-test scenarios.",
  "strategicTradeoffs": "Qualitative trade-offs beyond raw cost (reliability, user experience, vendor lock-in).",
  "disclaimer": "Decision support commentary generated by NVIDIA Nemotron via Nebius Token Factory. Not financial advice."
}`;

  const userPrompt = `Analyze the following verified TCO Comparison:
Project: "${analysis.projectTitle}"
Horizon: ${analysis.horizonYears} years
Scenario: ${analysis.scenario}
Currency: ${analysis.currency}
Lowest Cost Option: "${analysis.results[analysis.lowestCostOptionId]?.optionName || 'Option 1'}" (${analysis.currency} ${analysis.results[analysis.lowestCostOptionId]?.netTotalCost})
Highest Cost Option: "${analysis.results[analysis.highestCostOptionId]?.optionName || 'Option 2'}" (${analysis.currency} ${analysis.results[analysis.highestCostOptionId]?.netTotalCost})
Net Savings: ${analysis.currency} ${analysis.netSavings} (${analysis.percentageSavings}%)

Detailed Option Breakdown:
${Object.values(analysis.results)
  .map(
    opt => `
- ${opt.optionName}:
  * Upfront Acquisition: ${analysis.currency} ${opt.initialAcquisitionTotal}
  * Setup & Accessories: ${analysis.currency} ${opt.setupAccessoriesTotal}
  * Recurring Subscriptions: ${analysis.currency} ${opt.recurringTotal}
  * Maintenance & Repairs: ${analysis.currency} ${opt.maintenanceTotal}
  * Operating Utilities & Consumables: ${analysis.currency} ${opt.operatingTotal}
  * Replacement Outlays: ${analysis.currency} ${opt.replacementTotal} (${opt.replacementsOccurred} replacements)
  * Residual Recovery: -${analysis.currency} ${opt.residualRecoveryTotal}
  * Net Total Cost: ${analysis.currency} ${opt.netTotalCost} (Monthly Equivalent: ${analysis.currency} ${opt.monthlyEquivalentCost})
  * Audit Profile: ${opt.confidenceBreakdown.confirmedTotal} confirmed, ${opt.confidenceBreakdown.userEstimateTotal} user estimates, ${opt.confidenceBreakdown.missingCount} missing items.
`
  )
  .join('\n')}

Top Key Drivers:
${analysis.keyDrivers.map(d => `* ${d.title}: ${d.description}`).join('\n')}

Generate the structured JSON analysis now.`;

  const controller = new AbortController();
  const timeoutId = setTimeout(() => controller.abort(), timeoutMs);

  try {
    const response = await fetch(`${baseUrl}/chat/completions`, {
      method: 'POST',
      headers: {
        'Content-Type': 'application/json',
        Authorization: `Bearer ${apiKey}`,
      },
      body: JSON.stringify({
        model,
        messages: [
          { role: 'system', content: systemPrompt },
          { role: 'user', content: userPrompt },
        ],
        temperature: 0.2,
        max_tokens: 1500,
      }),
      signal: controller.signal,
    });

    clearTimeout(timeoutId);

    if (!response.ok) {
      const errText = await response.text().catch(() => 'Unknown error');
      console.error(`Nebius API returned status ${response.status}: ${errText.substring(0, 300)}`);
      // Fallback with error disclosure
      const fallback = generateMockNemotronReview(analysis);
      fallback.disclaimer = `[NOTICE: Nebius API request failed with status ${response.status}. Served validated fallback reasoning.]`;
      return fallback;
    }

    const data = await response.json();
    const content = data?.choices?.[0]?.message?.content;

    if (!content) {
      throw new Error('Empty response from Nebius Token Factory model');
    }

    // Parse JSON from model output (handling optional markdown backticks ```json ... ```)
    let cleaned = content.trim();
    if (cleaned.startsWith('```json')) {
      cleaned = cleaned.replace(/^```json\s*/, '').replace(/\s*```$/, '');
    } else if (cleaned.startsWith('```')) {
      cleaned = cleaned.replace(/^```\s*/, '').replace(/\s*```$/, '');
    }

    const parsed = JSON.parse(cleaned);

    return {
      executiveSummary: parsed.executiveSummary || 'Summary unavailable.',
      lowestCostExplanation: parsed.lowestCostExplanation || 'Analysis generated.',
      driverBreakdown: Array.isArray(parsed.driverBreakdown) ? parsed.driverBreakdown : [],
      missingAssumptionsFlags: Array.isArray(parsed.missingAssumptionsFlags) ? parsed.missingAssumptionsFlags : [],
      hiddenCostSuggestions: Array.isArray(parsed.hiddenCostSuggestions) ? parsed.hiddenCostSuggestions : [],
      scenarioSensitivityNotes: parsed.scenarioSensitivityNotes || '',
      strategicTradeoffs: parsed.strategicTradeoffs || '',
      disclaimer: `Verified live inference generated by NVIDIA Nemotron (${model}) via Nebius Token Factory. Decision support only.`,
      isMock: false,
      modelUsed: model,
      timestamp: new Date().toISOString(),
    };
  } catch (err: any) {
    clearTimeout(timeoutId);
    console.error('Error invoking Nebius Token Factory Nemotron model:', err.message || err);
    const fallback = generateMockNemotronReview(analysis);
    fallback.disclaimer = `[FALLBACK: Nebius connection ${err.name === 'AbortError' ? 'timed out after 25s' : 'encountered an error'}. Served verified deterministic reasoning.]`;
    return fallback;
  }
}
